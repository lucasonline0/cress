const { _electron: electron } = require('playwright');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cress-gui-'));
  const repo = path.join(dir, 'project'); fs.mkdirSync(repo);
  const git = (...args) => execFileSync('git', ['-C', repo, ...args]);
  git('init', '-q'); git('config', 'user.email', 'test@example.com'); git('config', 'user.name', 'Test');
  const source = path.join(repo, 'users.ts');
  fs.writeFileSync(source, "@Controller('users')\nclass Users { @Get() @Roles('ADMIN') list() {} }\n");
  const routes = Array.from({ length: 65 }, (_, index) =>
    `@Get('segment-${index}/${'nested/'.repeat(12)}:resourceId') route${index}() {}`).join('\n');
  fs.writeFileSync(path.join(repo, 'many.ts'), `@Controller('resources')\nclass Resources { ${routes} }\n`);
  const contract = path.join(dir, 'openapi.yaml');
  fs.writeFileSync(contract, 'openapi: 3.0.0\npaths:\n  /missing:\n    post: {}\n');
  git('add', '.'); git('commit', '-qm', 'baseline');
  fs.writeFileSync(source, "@Controller('users')\nclass Users { @Get() @Roles('USER') list() {} }\n");
  fs.writeFileSync(path.join(repo, '.cress.json'), JSON.stringify({ policies: [{ framework: 'nestjs', method: 'GET', path: '/users', requiredDeclarations: ['ADMIN'] }] }));
  const app = await electron.launch(process.env.CRESS_PACKAGED_EXECUTABLE ? { executablePath: process.env.CRESS_PACKAGED_EXECUTABLE, args: ['--disable-gpu'], cwd: dir } : { args: ['--disable-gpu', 'desktop-dist/main/main.cjs'] });
  try {
    const w = await app.firstWindow();
    const capture = async name => {
      if (process.env.CRESS_SCREENSHOT_DIR) {
        fs.mkdirSync(process.env.CRESS_SCREENSHOT_DIR, { recursive: true });
        await w.screenshot({ path: path.join(process.env.CRESS_SCREENSHOT_DIR, name + '.png') });
      }
    };
    const navigate = name => w.getByRole('navigation', { name: 'Workspace' }).getByRole('button', { name, exact: true }).click();
    await w.emulateMedia({ colorScheme: 'light' });
    await w.getByRole('button', { name: 'Open project', exact: true }).waitFor();
    if (await w.getByLabel('Git baseline').count()) throw new Error('Review form appeared on the welcome screen');
    await capture('01-welcome-light');
    if (await w.getByRole('button', { name: 'Try the example' }).count()) throw new Error('Example option must not appear');
    await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }); }, repo);
    if (await w.getByRole('button', { name: 'Check for Cress updates' }).count()) throw new Error('Update check must not be permanently visible');
    if (await w.locator('.update-notice').count()) throw new Error('Update status banner must not be present');
    await w.getByRole('button', { name: 'Open project', exact: true }).click();
    await w.getByRole('heading', { name: 'Overview', exact: true }).waitFor({ timeout: 30000 });
    await w.getByRole('button', { name: /Routes with policies.*1/ }).waitFor();
    await capture('02-overview-light');

    await navigate('Access Matrix');
    await w.getByRole('heading', { name: 'Create your first access profile' }).waitFor();
    await capture('03-matrix-empty-light');
    await w.getByRole('button', { name: 'Create profile' }).click();
    await w.getByLabel('Profile name').fill('ADMIN');
    await w.getByRole('dialog').getByRole('button', { name: 'Create profile' }).click();
    await w.getByLabel('Search matrix routes').fill('/users');
    await w.getByLabel('ADMIN GET /users .').selectOption('conditional');
    await w.getByLabel('Access condition', { exact: true }).fill('Own resource');
    await w.getByRole('button', { name: 'Apply' }).click();
    if (await w.getByLabel('ADMIN GET /users .').inputValue() !== 'conditional') throw new Error('Conditional expectation did not apply');
    await w.getByLabel('ADMIN GET /users .').selectOption('allow');
    await w.getByRole('button', { name: 'Save policies' }).click();
    await w.getByText('Policies saved to .cress.json.').waitFor();
    const saved = JSON.parse(fs.readFileSync(path.join(repo, '.cress.json'), 'utf8'));
    if (saved.accessMatrix.entries[0].expectations[0].access !== 'allow' || saved.policies.length !== 1) throw new Error('Policy persistence failed');
    await capture('04-matrix-light');

    await navigate('Access Explorer');
    await w.getByLabel('Search routes').fill('users');
    const result = w.locator('.route').first();
    await result.focus();
    await w.keyboard.press('Enter');
    await w.getByRole('heading', { name: 'Source declarations' }).waitFor();
    await w.getByRole('button', { name: 'Open in Matrix' }).click();
    await w.getByRole('heading', { name: 'GET /users', exact: true }).waitFor();
    await w.getByRole('button', { name: 'Open in Explorer' }).click();
    await w.getByRole('button', { name: 'Open in Test Studio' }).click();
    await w.getByText('No runner detected. Choose one available in your project.').waitFor();
    await w.getByLabel('Test runner').selectOption('jest');
    await w.getByLabel('Own and third-party resources').check();
    await w.getByLabel('Resource scenario profile').selectOption('ADMIN');
    await w.getByLabel('User ID', { exact: true }).fill('user-1');
    await w.getByLabel('Owned resource ID', { exact: true }).fill('own-1');
    await w.getByLabel('Third-party resource ID', { exact: true }).fill('other-1');
    await w.getByRole('button', { name: 'Generate template' }).click();
    await w.getByLabel('Generated test code').waitFor();
    await w.locator('main').evaluate(main => main.scrollTo(0, 0));
    if (!(await w.getByLabel('Generated test code').inputValue()).includes('other-1')) throw new Error('Missing resource test scenario');
    await capture('05-studio-light');

    await w.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
    await w.setViewportSize({ width: 780, height: 650 });
    await navigate('Coverage & Drift');
    await w.getByRole('button', { name: /With policy.*1/ }).waitFor();
    await capture('06-coverage-dark-compact');
    await w.getByRole('button', { name: 'OpenAPI Drift', exact: true }).click();
    await w.getByRole('heading', { name: 'No OpenAPI document imported' }).waitFor();
    await capture('07-drift-empty-dark-compact');
    await app.evaluate(({ dialog }, paths) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [paths.contract] });
      dialog.showSaveDialog = async () => ({ canceled: false, filePath: paths.html });
    }, { contract, html: path.join(dir, 'coverage.html') });
    await w.getByRole('button', { name: 'Import OpenAPI', exact: true }).click();
    await w.getByText(contract, { exact: true }).first().waitFor();
    await w.getByRole('button', { name: contract + ':4' }).click();
    await w.getByRole('dialog', { name: 'OpenAPI source' }).getByText('4 →     post: {}', { exact: false }).waitFor();
    await w.keyboard.press('Escape');
    await capture('08-drift-imported-dark-compact');
    await w.getByRole('button', { name: 'Export HTML', exact: true }).click();
    await w.getByText('Report exported.').waitFor();
    const exported = fs.readFileSync(path.join(dir, 'coverage.html'), 'utf8');
    if (!exported.includes('<table>') || !exported.includes('Only in contract') || !exported.includes('/missing')) throw new Error('Missing coverage report content');

    await navigate('Access Explorer');
    await w.locator('.route').first().focus();
    await w.keyboard.press('ArrowDown');
    if (await w.locator('.route').nth(1).getAttribute('aria-pressed') !== 'true') throw new Error('Keyboard route selection failed');
    if (await w.locator('main').evaluate(main => main.scrollWidth > main.clientWidth)) throw new Error('Explorer overflows the viewport');
    await capture('09-explorer-dark-compact');
    await w.screenshot({ path: process.env.CRESS_SCREENSHOT || path.join(os.tmpdir(), 'cress-desktop.png') });
    await app.evaluate(({ dialog }, paths) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [paths.repo] }); dialog.showSaveDialog = async (_window, options) => ({ canceled: false, filePath: options.defaultPath.endsWith('.html') ? paths.output : paths.json }); }, { repo, output: path.join(dir, 'report.html'), json: path.join(dir, 'diff.json') });
    await w.getByRole('button', { name: 'Switch project' }).click();
    await w.getByRole('heading', { name: 'Overview', exact: true }).waitFor({ timeout: 30000 });
    await navigate('Authorization Review');
    await w.getByRole('button', { name: 'Compare' }).click();
    const policy = w.locator('.policy-results').getByRole('heading', { name: 'GET /users', exact: true });
    await policy.waitFor({ timeout: 30000 });
    await w.getByLabel('Policy status').selectOption('UNKNOWN');
    if (await policy.count()) throw new Error('Policy filter did not apply');
    await w.getByLabel('Policy status').selectOption('ALL');
    await w.locator('.route').filter({ hasText: 'Declaration changed' }).first().waitFor({ timeout: 30000 });
    await w.locator('.route').filter({ hasText: 'Declaration changed' }).first().click();
    await w.locator('.details').getByText("@Roles('ADMIN')").waitFor();
    await w.locator('.details').getByText("@Roles('USER')").waitFor();
    await capture('10-review-changes-dark-compact');
    await w.getByRole('button', { name: 'Export JSON' }).click();
    await w.getByText('Export saved.').waitFor();
    if (!JSON.parse(fs.readFileSync(path.join(dir, 'diff.json'), 'utf8')).changes.length) throw new Error('Missing diff JSON changes');
    await w.getByRole('button', { name: 'Export HTML' }).click();
    await w.getByText('Export saved.').waitFor();
    if (!fs.readFileSync(path.join(dir, 'report.html'), 'utf8').includes('Authorization review')) throw new Error('Missing report content');
    git('add', '.'); git('commit', '-qm', 'accept local changes');
    await w.getByRole('button', { name: 'Compare' }).click();
    await w.getByRole('heading', { name: 'No static changes found' }).waitFor();
    await capture('11-review-empty-dark-compact');
    await w.setViewportSize({ width: 1280, height: 820 });
    const mixed = path.join(dir, 'mixed'); fs.mkdirSync(path.join(mixed, 'api/routes'), { recursive: true }); fs.mkdirSync(path.join(mixed, 'web/app/api/data'), { recursive: true });
    const mixedGit = (...args) => execFileSync('git', ['-C', mixed, ...args]);
    mixedGit('init', '-q'); mixedGit('config', 'user.email', 'test@example.com'); mixedGit('config', 'user.name', 'Test');
    fs.writeFileSync(path.join(mixed, 'api/go.mod'), 'module example\nrequire github.com/go-chi/chi/v5 v5.0.0\n');
    const goFile = path.join(mixed, 'api/main.go');
    fs.writeFileSync(goFile, 'package main\nimport ("github.com/go-chi/chi/v5"; routes "example/routes")\nfunc f(){r:=chi.NewRouter();r.Use(oldGuard);r.Get("/chi",handler);routes.Register(r)}');
    fs.writeFileSync(path.join(mixed, 'api/routes/routes.go'), 'package policies\nimport "github.com/go-chi/chi/v5"\nfunc Register(r chi.Router){r.Get("/cross",handler)}');
    fs.writeFileSync(path.join(mixed, 'web/package.json'), '{"dependencies":{"next":"1"}}');
    fs.writeFileSync(path.join(mixed, 'web/app/api/data/route.ts'), 'export function GET() { return auth() }');
    mixedGit('add', '.'); mixedGit('commit', '-qm', 'baseline');
    fs.writeFileSync(goFile, 'package main\nimport ("github.com/go-chi/chi/v5"; routes "example/routes")\nfunc f(){r:=chi.NewRouter();r.Use(newGuard);r.Get("/chi",handler);routes.Register(r)}');
    await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }); }, mixed);
    await w.getByRole('button', { name: 'Switch project' }).click();
    await w.getByRole('button', { name: 'Rescan' }).waitFor({ timeout: 30000 });
    await w.getByRole('button', { name: 'Overview' }).click();
    await w.getByRole('heading', { name: 'Detected applications' }).waitFor({ timeout: 30000 });
    await w.getByRole('button', { name: /api.*Go \/ Chi.*2 routes/ }).waitFor();
    await w.getByRole('button', { name: /web.*Next\.js.*1 route/ }).waitFor();
    await navigate('Access Explorer');
    await w.getByLabel('Search routes').fill('');
    await w.getByLabel('Framework').selectOption('go-chi');
    await w.locator('.route').getByText('/chi', { exact: true }).click();
    await w.getByText('newGuard', { exact: true }).waitFor();
    await w.locator('.route').getByText('/cross', { exact: true }).click();
    await w.getByText('api/routes/routes.go:3', { exact: true }).waitFor();
    await w.getByText('newGuard', { exact: true }).waitFor();
    await w.getByLabel('Framework').selectOption('nextjs');
    await w.getByRole('heading', { name: 'Select a route', exact: true }).waitFor();
    await w.getByText('/api/data', { exact: true }).click();
    await w.getByText('auth()', { exact: true }).waitFor();
    await navigate('Authorization Review');
    await w.getByRole('button', { name: 'Compare' }).click();
    await w.locator('.route').filter({ hasText: 'Declaration changed' }).first().click({ timeout: 30000 });
    await w.getByText('oldGuard', { exact: true }).waitFor();
    await w.getByText('newGuard', { exact: true }).waitFor();
    await w.getByRole('button', { name: 'Export HTML' }).click();
    await w.getByText('Export saved.').waitFor();
    if (!fs.readFileSync(path.join(dir, 'report.html'), 'utf8').includes('go-chi')) throw new Error('Missing mixed report data');
    const reportPromise = app.waitForEvent('window');
    await app.evaluate(({ BrowserWindow }, file) => { globalThis.__cressReportTestWindow = new BrowserWindow({ show: false, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } }); void globalThis.__cressReportTestWindow.loadFile(file); }, path.join(dir, 'report.html'));
    const report = await reportPromise;
    await report.locator('[data-route]').first().waitFor();
    await report.locator('#framework').selectOption('go-chi');
    if (await report.locator('[data-route]:visible').count() !== 2) throw new Error('Offline framework filter did not select the Chi routes');
    await report.locator('#framework').selectOption('nextjs');
    if (await report.locator('[data-route]:visible').count() !== 1) throw new Error('Offline framework filter did not select the Next.js route');
    await report.close();
    console.log('Desktop smoke passed: navigation, Matrix persistence, Studio generation, Coverage, OpenAPI, Git review and exports');
  } finally { await app.close(); fs.rmSync(dir, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exit(1); });
